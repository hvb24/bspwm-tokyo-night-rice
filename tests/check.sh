#!/bin/bash
# Static checks that run without a desktop session. Run from anywhere: ./tests/check.sh
cd "$(dirname "$0")/.." || exit 1
fail=0
ok()   { printf '  ok    %s\n' "$1"; }
bad()  { printf '  FAIL  %s\n' "$1"; fail=1; }

echo "== shell syntax"
while IFS= read -r f; do
  first=$(head -n1 "$f")
  case "$first" in
    *sh*) if [[ "$first" == *bash* ]]; then bash -n "$f"; else sh -n "$f"; fi ;;
    *) continue ;;
  esac
  [ $? -eq 0 ] && ok "$f" || bad "$f"
done < <(find . -type f \( -name '*.sh' -o -path './config/bspwm/bspwmrc' -o -path './config/theme/machine.sh' \) -not -path './.git/*')

echo "== python"
while IFS= read -r f; do
  python3 -I -m py_compile "$f" 2>/dev/null && ok "$f" || bad "$f"
done < <(find . -name '*.py' -not -path './.git/*')

echo "== toml / xml"
python3 -c "import tomllib;tomllib.load(open('config/alacritty/alacritty.toml','rb'))" && ok alacritty.toml || bad alacritty.toml
python3 -c "import tomllib;tomllib.load(open('config/starship.toml','rb'))" && ok starship.toml || bad starship.toml
for x in config/Thunar/uca.xml config/xfce4/xfconf/xfce-perchannel-xml/thunar.xml; do
  python3 -c "import xml.dom.minidom as m,sys;m.parse(sys.argv[1])" "$x" && ok "$x" || bad "$x"
done

echo "== keybindings (no duplicates, every brace group expands)"
SXHKDRC="$PWD/config/sxhkd/sxhkdrc" python3 config/bspwm/scripts/keys.py --check >/tmp/keys-check.$$ 2>&1 && ok "sxhkdrc" || { cat /tmp/keys-check.$$; bad "sxhkdrc"; }
rm -f /tmp/keys-check.$$

echo "== rofi themes (needs rofi installed; colours generated by apply.sh in a temp home)"
if command -v rofi >/dev/null 2>&1; then
  tmp=$(mktemp -d)
  mkdir -p "$tmp/.config" && cp -r config/. "$tmp/.config/"
  if HOME="$tmp" RICE_NO_BSPC=1 "$tmp/.config/theme/apply.sh" >/dev/null 2>&1 && [ -f "$tmp/.config/rofi/colors.rasi" ]; then
    for f in config custom menu grid wallpaper; do
      (cd "$tmp/.config/rofi" && HOME="$tmp" rofi -rasi-validate "$f.rasi" >/dev/null 2>&1) && ok "$f.rasi" || bad "$f.rasi"
    done
  else
    bad "apply.sh did not generate rofi/colors.rasi"
  fi
  rm -rf "$tmp"
else
  echo "  skip  rofi not installed"
fi

echo "== no personal data or leftover machine values"
if grep -rnE "/home/[a-z]|@gmail|BEGIN (RSA|OPENSSH|PRIVATE)|ghp_[A-Za-z0-9]{20}" config docs README.md install.sh uninstall.sh 2>/dev/null; then
  bad "personal data found (see above)"
else
  ok "clean"
fi

echo
[ $fail -eq 0 ] && echo "all checks passed" || { echo "some checks failed"; exit 1; }
