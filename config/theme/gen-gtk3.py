#!/usr/bin/env python3
"""Generate the GTK3 theme "TokyoNight" by recolouring GTK's built-in Adwaita-dark stylesheet
with the palette from ~/.config/theme/palette.sh. Adwaita's CSS has its colours baked in as hex,
so overriding named colours is not enough; instead every grey/blue/green/red/orange is remapped.
Cached: only regenerates when palette.sh (or this script) is newer than the output."""
import colorsys, os, re, sys
home = os.path.expanduser('~')
pal_file = home + '/.config/theme/palette.sh'
out_dir = home + '/.themes/TokyoNight/gtk-3.0'
out = out_dir + '/gtk.css'
if os.path.exists(out) and os.path.getmtime(out) > max(os.path.getmtime(pal_file), os.path.getmtime(__file__)):
    sys.exit(0)

import gi
gi.require_version('Gtk', '3.0')
from gi.repository import Gio, Gtk   # noqa: E402  (importing Gtk registers the theme resources)

pal = {}
for line in open(pal_file):
    m = re.match(r'^([A-Z_]+)="([0-9a-fA-F]{6})"', line)
    if m:
        pal[m.group(1)] = tuple(int(m.group(2)[i:i+2], 16) for i in (0, 2, 4))

def mix(a, b, t):
    return tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3))
def tohex(c):
    return '#%02x%02x%02x' % tuple(max(0, min(255, v)) for v in c)

BLACK, WHITE = (0, 0, 0), (255, 255, 255)
anchors = [  # (adwaita grey value, tokyo-night colour)
    (0x00, mix(pal['BG_ALT'], BLACK, 0.55)), (0x1b, mix(pal['BG_ALT'], BLACK, 0.25)),
    (0x2d, pal['BG_ALT']), (0x35, pal['BG']), (0x40, pal['SURFACE']), (0x5b, pal['BORDER']),
    (0x8a, pal['FG_MUTED']), (0x91, mix(pal['FG_MUTED'], pal['FG'], 0.15)),
    (0xbb, mix(pal['FG_MUTED'], pal['FG'], 0.6)), (0xee, pal['FG']), (0xff, mix(pal['FG'], WHITE, 0.3)),
]
def map_grey(v):
    for (v0, c0), (v1, c1) in zip(anchors, anchors[1:]):
        if v <= v1:
            return mix(c0, c1, (v - v0) / (v1 - v0) if v1 > v0 else 0)
    return anchors[-1][1]

dark = mix(pal['BG_ALT'], BLACK, 0.3)
def family(h):
    h *= 360
    if 190 <= h <= 265: return pal['BLUE']
    if 70 <= h < 170:  return pal['GREEN']
    if h < 18 or h > 340: return pal['RED']
    if 18 <= h < 45:   return pal['ORANGE']
    if 45 <= h < 70:   return pal['YELLOW']
    return None
def map_rgb(r, g, b):
    if max(r, g, b) - min(r, g, b) <= 6:                       # grey
        return map_grey(round((r + g + b) / 3))
    h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    tgt = family(h)
    if tgt is None:
        return (r, g, b)
    lt = colorsys.rgb_to_hls(*[x / 255 for x in tgt])[1]
    return mix(dark, tgt, min(1.0, l / lt))

css = Gio.resources_lookup_data('/org/gtk/libgtk/theme/Adwaita/gtk-contained-dark.css', 0).get_data().decode()
css = re.sub(r'#([0-9a-fA-F]{6})\b', lambda m: tohex(map_rgb(*[int(m.group(1)[i:i+2], 16) for i in (0, 2, 4)])), css)
def rgba(m):
    r, g, b = int(m.group(1)), int(m.group(2)), int(m.group(3))
    if (r, g, b) == (0, 0, 0):      # keep black shadows black
        return m.group(0)
    nr, ng, nb = map_rgb(r, g, b)
    return 'rgba(%d, %d, %d, %s)' % (nr, ng, nb, m.group(4))
css = re.sub(r'rgba\(\s*(\d+),\s*(\d+),\s*(\d+),\s*([0-9.]+)\)', rgba, css)

hexs = {k: tohex(v) for k, v in pal.items()}
polish = '''
/* ================= TokyoNight polish (rounded, flat, quiet) ================= */
button, entry, spinbutton, combobox button { border-radius: 8px; }
button { padding: 4px 12px; }
toolbar { padding: 4px 8px; border-bottom: 1px solid @borders; }
toolbar button { border-radius: 8px; }
headerbar, .titlebar { border-bottom: 1px solid @borders; box-shadow: none; }
menu, .menu, .popup, popover { border-radius: 10px; border: 1px solid @borders; }
menuitem { border-radius: 6px; margin: 1px 4px; padding: 5px 8px; }
menuitem:hover { background-color: alpha(@theme_selected_bg_color, 0.45); }
iconview:selected, treeview.view:selected, .view:selected { border-radius: 6px; }
.sidebar, .sidebar .view, .sidebar treeview.view { background-color: @content_view_bg; }
statusbar { color: @insensitive_fg_color; }
scrollbar slider { border-radius: 8px; min-width: 6px; min-height: 6px; }
tooltip { border-radius: 8px; }
'''
os.makedirs(out_dir, exist_ok=True)
open(out, 'w').write('/* GENERATED by ~/.config/theme/gen-gtk3.py from palette.sh - do not edit */\n' + css + polish)
print('gtk3 theme written:', out, len(css), 'bytes')
